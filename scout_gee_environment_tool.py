def _results(
    artifacts: dict[str, dict[str, Any]],
    *,
    include_grid: bool,
    include_timeseries: bool,
    limit: int,
) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    if include_grid:
        rows.extend(
            _feature_rows(
                "soil_moisture_grid",
                artifacts["soil_moisture_grid"],
                limit=limit,
            )
        )
        rows.extend(
            _feature_rows(
                "antecedent_rain_grid",
                artifacts["antecedent_rain_grid"],
                limit=limit,
            )
        )
    if include_timeseries:
        rows.extend(
            _timeseries_rows(
                "smap_l4_timeseries",
                artifacts["smap_timeseries"],
                limit=limit,
            )
        )
        rows.extend(
            _timeseries_rows(
                "gpm_imerg_timeseries",
                artifacts["gpm_timeseries"],
                limit=limit,
            )
        )
    return rows[:limit]


def _feature_rows(kind: str, payload: dict[str, Any], *, limit: int) -> list[dict[str, Any]]:
    features = payload.get("features")
    if not isinstance(features, list):
        return []
    rows = []
    for feature in features[:limit]:
        if not isinstance(feature, dict):
            continue
        properties = feature.get("properties") if isinstance(feature.get("properties"), dict) else {}
        geometry = feature.get("geometry") if isinstance(feature.get("geometry"), dict) else {}
        rows.append(
            {
                "result_kind": kind,
                "label": properties.get("name") or properties.get("label") or kind,
                "properties": _compact_dict(properties, max_keys=8),
                "geometry_type": geometry.get("type"),
                "candidate_only": True,
                "runtime_safety_truth": False,
            }
        )
    return rows


def _timeseries_rows(kind: str, payload: dict[str, Any], *, limit: int) -> list[dict[str, Any]]:
    records: list[Any] = []
    for key in ("timeseries", "records", "events", "items", "timeline"):
        value = payload.get(key)
        if isinstance(value, list):
            records = value
            break
    rows = []
    for record in records[:limit]:
        if not isinstance(record, dict):
            continue
        rows.append(
            {
                "result_kind": kind,
                "time": record.get("time") or record.get("timestamp") or record.get("valid_time"),
                "properties": _compact_dict(record, max_keys=8),
                "candidate_only": True,
                "runtime_safety_truth": False,
            }
        )
    return rows


def _compact_dict(value: dict[str, Any], *, max_keys: int) -> dict[str, Any]:
    return {key: value[key] for key in list(value)[:max_keys]}


def _provenance_summary(source_report: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "loaded_sources": [
            item["source_kind"] for item in source_report if item.get("status") == "loaded"
        ],
        "missing_or_error_sources": [
            item["source_kind"]
            for item in source_report
            if item.get("status") in {"missing", "error"}
        ],
        "raw_response_hashes": [
            item["raw_response_hash"]
            for item in source_report
            if item.get("raw_response_hash")
        ],
        "collection_ids": sorted(
            {
                collection_id
                for item in source_report
                for collection_id in item.get("collection_ids", [])
                if str(collection_id).strip()
            }
        ),
        "candidate_only": True,
        "runtime_safety_truth": False,
        "human_review_required": True,
    }


def _source_status(available_artifact_count: int) -> str:
    if available_artifact_count == 0:
        return "missing"
    if available_artifact_count < 4:
        return "partial"
    return "candidate_only"


def _bounded_limit(value: int) -> int:
    return max(1, min(MAX_RESULT_LIMIT, int(value or DEFAULT_RESULT_LIMIT)))


def _bool_value(value: bool | str | None, *, default: bool) -> bool:
    if value is None or value == "":
        return default
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() not in {"0", "false", "no", "off"}


def _float_or_default(value: float | int | str | None, *, default: float) -> float:
    parsed = _float_or_none(value)
    return default if parsed is None else parsed


def _float_or_none(value: Any) -> float | None:
    if value is None or value == "":
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _dedupe_text(values: list[str] | Any) -> list[str]:
    seen = set()
    result = []
    for value in values:
        text = str(value).strip()
        if not text or text in seen:
            continue
        seen.add(text)
        result.append(text)
    return result


