def _load_artifact(
    root: Path,
    project: dict[str, Any],
    *,
    explicit_path: str | None,
    ref_keys: tuple[str, ...],
    fallbacks: tuple[str, ...],
    source_kind: str,
    source_report: list[dict[str, Any]],
) -> dict[str, Any]:
    refs = _candidate_paths(
        root,
        project,
        explicit_path=explicit_path,
        ref_keys=ref_keys,
        fallbacks=fallbacks,
    )
    for ref in refs:
        path = _resolve_project_path(root, ref)
        if not path.exists() or not path.is_file():
            continue
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            source_report.append(
                _source_report(
                    source_kind,
                    ref,
                    status="error",
                    error=str(exc),
                )
            )
            return {}
        if isinstance(payload, dict):
            source_report.append(
                _source_report(
                    source_kind,
                    ref,
                    status="loaded",
                    payload=payload,
                )
            )
            return payload
        if isinstance(payload, list):
            normalized = {"items": payload}
            source_report.append(
                _source_report(
                    source_kind,
                    ref,
                    status="loaded",
                    payload=normalized,
                )
            )
            return normalized
        source_report.append(
            _source_report(
                source_kind,
                ref,
                status="error",
                error="JSON artifact must be an object or list",
            )
        )
        return {}
    source_report.append(_source_report(source_kind, refs[0], status="missing"))
    return {}


def _candidate_paths(
    root: Path,
    project: dict[str, Any],
    *,
    explicit_path: str | None,
    ref_keys: tuple[str, ...],
    fallbacks: tuple[str, ...],
) -> list[str]:
    refs: list[str] = []
    if explicit_path:
        refs.append(explicit_path)
    for key in ref_keys:
        value = project.get(key)
        if isinstance(value, str) and value.strip():
            refs.append(value.strip())
    refs.extend(fallbacks)
    deduped: list[str] = []
    seen = set()
    for ref in refs:
        normalized = _project_ref(root, ref)
        if normalized and normalized not in seen:
            seen.add(normalized)
            deduped.append(normalized)
    return deduped


def _project_ref(root: Path, ref: str) -> str:
    path = Path(str(ref))
    if path.is_absolute():
        try:
            return str(path.relative_to(root))
        except ValueError:
            return str(path)
    return str(path)


def _resolve_project_path(root: Path, ref: str) -> Path:
    path = Path(str(ref))
    if path.is_absolute():
        return path
    return root / path


def _load_json_object(path: Path) -> dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return payload if isinstance(payload, dict) else {}


def _source_report(
    source_kind: str,
    source_path: str,
    *,
    status: str,
    payload: dict[str, Any] | None = None,
    error: str | None = None,
) -> dict[str, Any]:
    report: dict[str, Any] = {
        "source_kind": source_kind,
        "source_path": source_path,
        "status": status,
        "candidate_only": True,
        "runtime_safety_truth": False,
        "human_review_required": True,
    }
    if error:
        report["error"] = error
    if payload:
        report.update(
            {
                "artifact_kind": payload.get("artifact_kind"),
                "schema_version": payload.get("schema_version"),
                "collection_ids": _collection_ids(payload),
                "dataset_ids": _collection_ids(payload),
                "source_refs": _source_refs(payload),
                "raw_response_hash": _raw_hash(payload),
                "stale_risk": _stale_risk(payload),
                "request_timestamp": _request_timestamp(payload),
                "normalized_artifact_ref": payload.get("normalized_artifact_ref"),
            }
        )
    return {key: value for key, value in report.items() if value not in (None, [], {})}


